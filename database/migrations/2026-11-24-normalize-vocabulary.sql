BEGIN;

CREATE TABLE IF NOT EXISTS tu_vung_nghia (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id         integer NOT NULL REFERENCES tu_vung (id) ON DELETE CASCADE,
  meaning_vi      text NOT NULL,
  part_of_speech  text,
  position        smallint NOT NULL DEFAULT 1 CHECK (position > 0),
  UNIQUE (word_id, meaning_vi)
);

CREATE INDEX IF NOT EXISTS word_senses_word_position_idx
  ON tu_vung_nghia (word_id, position, id);
CREATE INDEX IF NOT EXISTS word_senses_meaning_trgm
  ON tu_vung_nghia USING gin (meaning_vi gin_trgm_ops);

CREATE TABLE IF NOT EXISTS bai_doc_tu_vung (
  reading_id            integer NOT NULL REFERENCES bai_doc (id) ON DELETE CASCADE,
  word_id               integer NOT NULL REFERENCES tu_vung (id) ON DELETE RESTRICT,
  sense_id              bigint REFERENCES tu_vung_nghia (id) ON DELETE SET NULL,
  position              smallint NOT NULL CHECK (position > 0),
  contextual_meaning_vi text,
  note_vi               text,
  PRIMARY KEY (reading_id, word_id),
  UNIQUE (reading_id, position)
);

CREATE INDEX IF NOT EXISTS reading_words_word_idx
  ON bai_doc_tu_vung (word_id);

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'tu_vung'
      AND column_name = 'meaning_vi'
  ) THEN
    INSERT INTO tu_vung_nghia (word_id, meaning_vi, part_of_speech, position)
    SELECT id, meaning_vi, part_of_speech, 1
    FROM tu_vung
    WHERE btrim(meaning_vi) <> ''
    ON CONFLICT (word_id, meaning_vi) DO NOTHING;
  END IF;
END
$$;

CREATE TEMP TABLE vocabulary_reading_import ON COMMIT DROP AS
SELECT r.id AS reading_id,
       c.hsk_level,
       btrim(item.value ->> 'hanzi') AS hanzi,
       btrim(coalesce(item.value ->> 'pinyin', '')) AS pinyin,
       nullif(btrim(item.value ->> 'meaningVi'), '') AS meaning_vi,
       item.ordinality AS source_position
FROM bai_doc r
JOIN khoa_hoc c ON c.id = r.course_id
CROSS JOIN LATERAL jsonb_array_elements(r.important_vocabulary)
  WITH ORDINALITY AS item(value, ordinality)
WHERE jsonb_typeof(item.value) = 'object'
  AND nullif(btrim(item.value ->> 'hanzi'), '') IS NOT NULL;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'tu_vung'
      AND column_name = 'meaning_vi'
  ) THEN
    INSERT INTO tu_vung (hanzi, pinyin, meaning_vi, part_of_speech, hsk_level)
    SELECT DISTINCT ON (hanzi, pinyin)
           hanzi, pinyin, coalesce(meaning_vi, hanzi), NULL, hsk_level
    FROM vocabulary_reading_import
    ORDER BY hanzi, pinyin, hsk_level, source_position
    ON CONFLICT (hanzi, pinyin) DO UPDATE
      SET hsk_level = CASE
        WHEN tu_vung.hsk_level IS NULL THEN EXCLUDED.hsk_level
        WHEN EXCLUDED.hsk_level IS NULL THEN tu_vung.hsk_level
        ELSE least(tu_vung.hsk_level, EXCLUDED.hsk_level)
      END;
  ELSE
    INSERT INTO tu_vung (hanzi, pinyin, hsk_level)
    SELECT DISTINCT ON (hanzi, pinyin)
           hanzi, pinyin, hsk_level
    FROM vocabulary_reading_import
    ORDER BY hanzi, pinyin, hsk_level, source_position
    ON CONFLICT (hanzi, pinyin) DO UPDATE
      SET hsk_level = CASE
        WHEN tu_vung.hsk_level IS NULL THEN EXCLUDED.hsk_level
        WHEN EXCLUDED.hsk_level IS NULL THEN tu_vung.hsk_level
        ELSE least(tu_vung.hsk_level, EXCLUDED.hsk_level)
      END;
  END IF;
END
$$;

WITH unique_senses AS (
  SELECT DISTINCT word.id AS word_id, source.meaning_vi
  FROM vocabulary_reading_import source
  JOIN tu_vung word ON word.hanzi = source.hanzi AND word.pinyin = source.pinyin
  WHERE source.meaning_vi IS NOT NULL
), ordered_senses AS (
  SELECT word_id,
         meaning_vi,
         (coalesce((SELECT max(s.position) FROM tu_vung_nghia s WHERE s.word_id = unique_senses.word_id), 0)
           + row_number() OVER (PARTITION BY word_id ORDER BY meaning_vi))::smallint AS position
  FROM unique_senses
)
INSERT INTO tu_vung_nghia (word_id, meaning_vi, position)
SELECT word_id, meaning_vi, position
FROM ordered_senses
ON CONFLICT (word_id, meaning_vi) DO NOTHING;

WITH unique_reading_words AS (
  SELECT DISTINCT ON (reading_id, hanzi, pinyin)
         reading_id, hanzi, pinyin, meaning_vi, source_position
  FROM vocabulary_reading_import
  ORDER BY reading_id, hanzi, pinyin, source_position
)
INSERT INTO bai_doc_tu_vung (reading_id, word_id, sense_id, position)
SELECT source.reading_id,
       word.id,
       sense.id,
       row_number() OVER (PARTITION BY source.reading_id ORDER BY source.source_position)::smallint
FROM unique_reading_words source
JOIN tu_vung word ON word.hanzi = source.hanzi AND word.pinyin = source.pinyin
LEFT JOIN tu_vung_nghia sense
  ON sense.word_id = word.id
 AND sense.meaning_vi = source.meaning_vi
ON CONFLICT (reading_id, word_id) DO NOTHING;

ALTER TABLE tu_vung
  DROP COLUMN IF EXISTS meaning_vi,
  DROP COLUMN IF EXISTS part_of_speech;

DROP INDEX IF EXISTS words_meaning_trgm;

COMMIT;
